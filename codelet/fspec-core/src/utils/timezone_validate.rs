/// Validate a timezone string (trimmed) against the IANA list. Returns
/// `Ok(())` when valid, or the full error `reason` string (parity with
/// `validateTimezone` in timezone.ts:51-94) on failure — including up to five
/// "Did you mean" suggestions, or the generic guidance line when none match.
pub fn validate_timezone(timezone: &str) -> Result<(), String> {
    if timezone.is_empty() {
        return Err("Timezone is required and must be a string".to_string());
    }
    let trimmed = timezone.trim();
    if VALID_TIMEZONES.contains(&trimmed) {
        return Ok(());
    }

    let lower_trimmed = trimmed.to_lowercase();
    let suggestions: Vec<&str> = VALID_TIMEZONES
        .iter()
        .copied()
        .filter(|tz| {
            let lower_tz = tz.to_lowercase();
            lower_tz.contains(&lower_trimmed)
                || lower_trimmed.contains(&lower_tz)
                || lower_tz.split('/').any(|part| part.contains(&lower_trimmed))
                || lower_trimmed.split('/').any(|part| lower_tz.contains(part))
        })
        .take(5)
        .collect();

    let mut reason = format!("Invalid timezone '{trimmed}'.");
    if suggestions.is_empty() {
        reason.push_str(
            " Use a valid IANA timezone like UTC, America/New_York, or Australia/Brisbane.",
        );
    } else {
        reason.push_str(&format!(" Did you mean: {}?", suggestions.join(", ")));
    }
    Err(reason)
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used)]
    use super::*;

    #[test]
    fn accepts_valid_zones_and_aliases() {
        assert!(validate_timezone("UTC").is_ok());
        assert!(validate_timezone("GMT").is_ok());
        assert!(validate_timezone("Etc/UTC").is_ok());
        assert!(validate_timezone("America/New_York").is_ok());
    }

    #[test]
    fn suggestions_match_ts() {
        assert_eq!(
            validate_timezone("York").unwrap_err(),
            "Invalid timezone 'York'. Did you mean: America/New_York?"
        );
        assert_eq!(
            validate_timezone("america/new_york").unwrap_err(),
            "Invalid timezone 'america/new_york'. Did you mean: America/Adak, America/Anchorage, America/Anguilla, America/Antigua, America/Araguaina?"
        );
        assert_eq!(
            validate_timezone("Australia").unwrap_err(),
            "Invalid timezone 'Australia'. Did you mean: Australia/Adelaide, Australia/Brisbane, Australia/Broken_Hill, Australia/Darwin, Australia/Eucla?"
        );
    }

    #[test]
    fn no_suggestions_uses_generic_guidance() {
        assert_eq!(
            validate_timezone("Not/AZone").unwrap_err(),
            "Invalid timezone 'Not/AZone'. Use a valid IANA timezone like UTC, America/New_York, or Australia/Brisbane."
        );
    }
}
