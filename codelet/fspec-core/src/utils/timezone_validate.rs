//! IANA timezone validator — Rust port of `src/utils/validators/timezone.ts`.
//!
//! The TS path validates a timezone string against the list produced by
//! `[...Object.keys(TIMEZONE_ALIASES), ...Intl.supportedValuesOf("timeZone")]`
//! — i.e. the four aliases (`UTC`, `GMT`, `Etc/UTC`, `Etc/GMT`) followed by
//! the Node-enumerated IANA zones in their (alphabetical) enumeration order.
//! On an invalid timezone it builds up to five "Did you mean" suggestions using
//! a substring/region match against that same ordered list.
//!
//! The original Rust port leaned on `chrono_tz::Tz` parsing, which both accepts
//! a slightly different set AND produces a generic error with no suggestions,
//! diverging from TS. This module embeds the exact Node-enumerated list (the
//! parity target is `node dist/index.js`, Node 18+ on this platform) so both
//! the accept/reject decision AND the suggestion text reach byte-parity.
//!
//! GENERATED list — keep in sync with the Node enumeration used by the TS CLI.

