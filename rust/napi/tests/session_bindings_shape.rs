// RPC-043 (disk-bloat fix): six tests in this file spawn nested
// `cargo build` / `cargo test --no-run` processes. They share three
// pieces of mutable state with each other:
//   1. `target/` — concurrent rustc workers race on .rlib outputs
//      under target/debug/deps/ and produce intermittent linker
//      errors when two cargo processes attempt the same link.
//   2. `rust/napi/index.d.ts` — regenerated by napi-derive on every
//      build. The noop build emits FEWER exports than the default
//      build because most #[napi] free functions are gated behind
//      `#[cfg(not(feature = "noop"))]`. If the noop build races with
//      `scenario_index_dts_is_byte_identical_to_pre_rpc043_baseline`
//      the dts-byte-identical scenario sees a truncated file and
//      reports phantom "removed exports" failures.
//   3. The workspace package cache lock at
//      `target/debug/.cargo-lock`, which cargo blocks on for several
//      minutes when multiple nested cargo processes race.
//
// Marking the six offending tests with `#[serial]` (via the
// `serial_test` crate, already a dev-dependency) serializes them
// among themselves while the other 48 tests continue to run in
// parallel — giving the best of both worlds: fast feedback for the
// pure-file-scan scenarios, race-free execution for the nested-cargo
// scenarios.
use serial_test::serial;

