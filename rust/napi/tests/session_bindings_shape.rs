/// codelet-napi crate root (one level above the tests dir).
fn napi_crate_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn napi_src() -> PathBuf {
    napi_crate_root().join("src")
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", path.display()))
}

/// Build a cargo `Command` that won't fill `target/debug/incremental/`
/// with multi-GB fingerprint trees. This is the disk-bloat fix
/// (RPC-043 retro): each nested `cargo build` / `cargo test --no-run`
/// invocation from within this test file writes its own incremental
/// cache for the napi + nanograph + arrow + datafusion + lance +
/// tantivy dep graph (~5-15 GB per profile/feature combination).
/// Forcing `CARGO_INCREMENTAL=0` keeps the .rlib outputs reachable for
/// reuse but skips the incremental fingerprint dirs entirely. The
/// user's interactive `cargo build` from the shell is unaffected
/// because the env var is scoped to the spawned child process.
fn cargo_cmd() -> std::process::Command {
    let mut cmd = std::process::Command::new(env!("CARGO"));
    cmd.env("CARGO_INCREMENTAL", "0");
    cmd
}

/// Strip `//`-style line comments so substring scans only see code.
fn strip_line_comments(src: &str) -> String {
    let mut out = String::with_capacity(src.len());
    for line in src.lines() {
        match line.find("//") {
            Some(pos) => {
                out.push_str(&line[..pos]);
                out.push('\n');
            }
            None => {
                out.push_str(line);
                out.push('\n');
            }
        }
    }
    out
}

/// Count occurrences of an `#[napi]` attribute immediately followed (on
/// the next line) by `pub fn` or `pub async fn` — i.e. free-function
/// wrappers. Excludes `#[napi(object)]`, `#[napi(constructor)]`,
/// `#[napi(getter)]`, etc.
fn count_napi_free_fn_wrappers(src: &str) -> usize {
    let mut count = 0usize;
    let lines: Vec<&str> = src.lines().collect();
    for (i, line) in lines.iter().enumerate() {
        let trimmed = line.trim_start();
        if trimmed == "#[napi]" {
            // Look at the next non-blank line for `pub fn` or `pub async fn`.
            for next in lines.iter().skip(i + 1) {
                let nt = next.trim_start();
                if nt.is_empty() {
                    continue;
                }
                if nt.starts_with("pub fn ")
                    || nt.starts_with("pub async fn ")
                    || nt.starts_with("pub(crate) fn ")
                    || nt.starts_with("pub(crate) async fn ")
                {
                    count += 1;
                }
                break;
            }
        }
    }
    count
}

