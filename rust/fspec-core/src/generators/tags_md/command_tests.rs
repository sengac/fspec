//! Feature: spec/features/generate-tags-md.feature
//!
//! The TAGS.md sections `fspec generate-tags-md` renders (COV-071): each test
//! writes spec/tags.json into a temporary project, runs the
//! `generate-tags-md` command through the dispatcher (the entry the CLI
//! subcommand calls) and reads spec/TAGS.md back. One test file per feature
//! (BUG-357).

#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::path::Path;

use serde_json::{json, Value};

use crate::{dispatch_command, DispatchRequest};

/// A schema-valid tags.json (every required top-level key present).
fn valid_tags() -> Value {
    json!({
        "categories": [
            { "name": "Phase Tags", "description": "Phase identification tags", "required": true,
              "tags": [ { "name": "@critical", "description": "Critical priority" } ] }
        ],
        "combinationExamples": [
            { "title": "Example 0", "tags": "@cli", "interpretation": ["CLI component"] }
        ],
        "usageGuidelines": {
            "requiredCombinations": { "title": "Required", "requirements": ["Must have a phase tag"], "minimumExample": "@phase-1" },
            "recommendedCombinations": { "title": "Recommended", "includes": ["component tag"], "recommendedExample": "@cli @phase-1" },
            "orderingConvention": { "title": "Ordering", "order": ["phase", "component"], "example": "@phase-1 @cli" }
        },
        "addingNewTags": {
            "process": [ { "step": "Step 1", "description": "Register the tag" } ],
            "namingConventions": ["lowercase-with-hyphens"],
            "antiPatterns": { "dont": [ { "description": "Overlap" } ], "do": [ { "description": "Reuse" } ] }
        },
        "queries": {
            "title": "Tag-Based Queries",
            "examples": [ { "description": "Find by tag", "command": "fspec list-tags" } ]
        },
        "statistics": {
            "lastUpdated": "2025-01-01T00:00:00Z",
            "phaseStats": [],
            "componentStats": [],
            "featureGroupStats": [],
            "updateCommand": "fspec tag-stats"
        },
        "validation": {
            "rules": [ { "rule": "Format", "description": "Tags must start with @" } ],
            "commands": [ { "description": "Validate", "command": "fspec validate-tags" } ]
        },
        "references": [ { "title": "Markdown tables", "url": "https://example.com/tables" } ]
    })
}

/// `valid_tags()` with `key` replaced by `value`.
fn tags_with(key: &str, value: Value) -> Value {
    let mut tags = valid_tags();
    tags[key] = value;
    tags
}

fn project_with_tags(tags: &Value) -> tempfile::TempDir {
    let tmp = tempfile::tempdir().expect("tempdir");
    let spec = tmp.path().join("spec");
    std::fs::create_dir_all(&spec).expect("mkdir spec");
    std::fs::write(
        spec.join("tags.json"),
        serde_json::to_string_pretty(tags).expect("ser tags"),
    )
    .expect("write tags.json");
    tmp
}

/// Runs `generate-tags-md` and returns spec/TAGS.md.
fn generate(root: &Path) -> String {
    let result = dispatch_command(DispatchRequest {
        command: "generate-tags-md".to_string(),
        args_json: "{}".to_string(),
        project_root: root.to_path_buf(),
    });
    assert!(result.success, "generate-tags-md failed: {result:?}");
    std::fs::read_to_string(root.join("spec").join("TAGS.md")).expect("read TAGS.md")
}

#[test]
fn auto_generation_warning_header_is_included() {
    // @step Given I have a valid file "spec/tags.json"
    let tmp = project_with_tags(&valid_tags());

    // @step When I run `fspec generate-tags-md`
    let md = generate(tmp.path());

    // @step Then the file "spec/TAGS.md" should start with:
    assert!(
        md.starts_with(
            "<!-- THIS FILE IS AUTO-GENERATED FROM spec/tags.json -->\n\
             <!-- DO NOT EDIT THIS FILE DIRECTLY -->\n\
             <!-- Edit spec/tags.json and run: fspec generate-tags-md -->\n"
        ),
        "{md}"
    );
}

#[test]
fn tag_combination_examples_are_formatted_correctly() {
    // @step Given I have "spec/tags.json" with combination examples:
    let tmp = project_with_tags(&tags_with(
        "combinationExamples",
        json!([
            {
                "title": "Example 1: Phase 1 Feature File Creation",
                "tags": "@cli @generator @feature-management",
                "interpretation": [
                    "Phase 1 feature",
                    "Belongs to CLI component",
                    "Part of feature management functionality"
                ]
            }
        ]),
    ));

    // @step When I run `fspec generate-tags-md`
    let md = generate(tmp.path());

    // @step Then "spec/TAGS.md" should contain:
    assert!(
        md.contains(
            "### Example 1: Phase 1 Feature File Creation\n\
             \n\
             ```gherkin\n\
             @cli @generator @feature-management\n\
             Feature: Create Feature File with Template\n\
             ```\n\
             \n\
             **Interpretation**:\n\
             - Phase 1 feature\n\
             - Belongs to CLI component\n\
             - Part of feature management functionality\n"
        ),
        "{md}"
    );
}

#[test]
fn tag_statistics_tables_are_generated() {
    // @step Given I have "spec/tags.json" with statistics:
    let tmp = project_with_tags(&tags_with(
        "statistics",
        json!({
            "lastUpdated": "2025-01-15T10:30:00Z",
            "phaseStats": [
                { "phase": "Phase 1", "total": 5, "complete": 5, "inProgress": 0, "planned": 0 }
            ],
            "componentStats": [
                { "component": "@cli", "count": 28, "percentage": "100%" }
            ],
            "featureGroupStats": [],
            "updateCommand": "fspec tag-stats"
        }),
    ));

    // @step When I run `fspec generate-tags-md`
    let md = generate(tmp.path());

    // @step Then "spec/TAGS.md" should contain phase statistics table
    assert!(
        md.contains(
            "### By Phase\n\n\
             | Phase | Total Features | Complete | In Progress | Planned |\n\
             |-------|----------------|----------|-------------|---------|\n\
             | Phase 1 | 5 | 5 | 0 | 0 |\n"
        ),
        "{md}"
    );

    // @step And it should contain component statistics table
    assert!(
        md.contains(
            "### By Component\n\n\
             | Component | Feature Count | Percentage |\n\
             |-----------|---------------|------------|\n\
             | @cli | 28 | 100% |\n"
        ),
        "{md}"
    );

    // @step And it should show last updated date
    assert!(
        md.contains("_Last updated: 2025-01-15T10:30:00Z_\n"),
        "{md}"
    );

    // @step And it should show update command
    assert!(
        md.contains("**Update Command**: `fspec tag-stats`\n"),
        "{md}"
    );
}

#[test]
fn anti_patterns_section_with_examples() {
    // @step Given I have "spec/tags.json" with anti-patterns:
    let mut adding = valid_tags()["addingNewTags"].clone();
    adding["antiPatterns"] = json!({
        "dont": [
            {
                "description": "Create overlapping tags",
                "example": "`@validate` and `@validation` → use `@validation`"
            }
        ],
        "do": [
            { "description": "Reuse existing tags through combinations" }
        ]
    });
    let tmp = project_with_tags(&tags_with("addingNewTags", adding));

    // @step When I run `fspec generate-tags-md`
    let md = generate(tmp.path());

    // @step Then "spec/TAGS.md" should contain:
    assert!(
        md.contains(
            "❌ **DON'T**:\n\
             - Create overlapping tags (`@validate` and `@validation` → use `@validation`)\n\
             \n\
             ✅ **DO**:\n\
             - Reuse existing tags through combinations\n"
        ),
        "{md}"
    );
}

#[test]
fn regeneration_is_idempotent() {
    // @step Given I have a valid file "spec/tags.json"
    let tmp = project_with_tags(&valid_tags());

    // @step When I run `fspec generate-tags-md`
    // @step And I save the content of "spec/TAGS.md"
    let saved = generate(tmp.path());

    // @step And I run `fspec generate-tags-md` again
    let again = generate(tmp.path());

    // @step Then the content of "spec/TAGS.md" should be identical to the saved version
    assert!(!saved.is_empty());
    assert_eq!(saved, again);
}
