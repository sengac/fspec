    Write-Host ""
    Write-Host "  3. Inside the container, install and use fspec:" -ForegroundColor White
    Write-Host "     " -NoNewline; Write-Host "npm install -g @sengac/fspec" -ForegroundColor Cyan
    Write-Host "     " -NoNewline; Write-Host "fspec" -ForegroundColor Cyan
    Write-Host ""
    Write-Host "For more information:" -ForegroundColor White
    Write-Host "  - ExitBox docs: https://github.com/cloud-exit/exitbox"
    Write-Host "  - fspec docs:   https://fspec.dev"
    Write-Host ""
}

Main
